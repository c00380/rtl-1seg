import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const sources = JSON.parse(await readFile(new URL('assets.json', import.meta.url), 'utf8'));
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

async function buildFile(source, file, directory) {
  const destination = new URL(file.name, directory);
  try {
    const bytes = await readFile(destination);
    if (bytes.length === file.size && sha256(bytes) === file.sha256) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const path = file.path ?? `${source.directory}/${file.name}`;
  const response = await fetch(
    `https://raw.githubusercontent.com/${source.repository}/${source.revision}/${path}`,
  );
  if (!response.ok) throw new Error(`${response.status}: ${path}`);
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.length !== file.size || sha256(bytes) !== file.sha256)
    throw new Error(`Asset does not match the pinned source: ${file.name}`);
  await writeFile(destination, bytes);
}

export async function buildAssetLicenses() {
  for (const [group, source] of Object.entries(sources)) {
    const directory = new URL(`../${group}/`, import.meta.url);
    await mkdir(directory, { recursive: true });
    for (const file of source.files)
      if (/LICENSE|AUTHORS|CONTRIBUTORS/i.test(file.name)) await buildFile(source, file, directory);
  }
}

export async function buildAssets(name) {
  for (const group of name ? [name] : Object.keys(sources)) {
    const source = sources[group];
    if (!source) throw new Error(`Unknown asset group: ${group}`);
    const directory = new URL(`../${group}/`, import.meta.url);
    await mkdir(directory, { recursive: true });
    const queue = [...source.files];
    await Promise.all(
      Array.from({ length: 6 }, async () => {
        for (let file; (file = queue.shift()); ) await buildFile(source, file, directory);
      }),
    );
    const files = source.files.filter((file) => !file.path);
    if (group === 'logos')
      await writeFile(
        new URL('index.js', directory),
        `// Generated by build/assets.js from KonomiTV ${source.revision}.\nexport const stationLogos = new Set(${JSON.stringify(
          files.map((file) => file.name),
          null,
          2,
        )});\n`,
      );
    await writeFile(
      new URL('SOURCE.json', directory),
      JSON.stringify({ repository: source.repository, revision: source.revision, files }, null, 2) +
        '\n',
    );
    console.log(`Built ${group} (${source.files.length} files)`);
  }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url)
  await buildAssets(process.argv[2]);
